mapping = {
    " ": _space, "!": _exclamation, "\"": _quotes, "#": _hashtag, "$": _dollar, "%": _percent, "&": _ampersand, "'": _quote,
    "(": _parentheses_open, ")": _parentheses_close, "*": _asterisk, "+": _plus, ",": _semicolon, "-": _minus, ".": _dot, "/": _slash,
    "0": _0, "1": _1, "2": _2, "3": _3, "4": _4, "5": _5, "6": _6, "7": _7, "8": _8, "9": _9,
    ":": _colon, ";": _semicolon, "<": _less, "=": _equal, ">": _greater, "?": _question, "@": _at,
    "A": A, "B": B, "C": C, "D": D, "E": E, "F": F, "G": G, "H": H, "I": I, "J": J, "K": K, "L": L, "M": M, "N": N, "O": O,
    "P": P, "Q": Q, "R": R, "S": S, "T": T, "U": U, "V": V, "W": W, "X": X, "Y": Y, "Z": Z
}


def generate(text: str) -> str:
    text = "  " + text
    full = ""
    for i in range(8):
        for char in text:
            full += mapping[char].splitlines()[i] + " "
        full += " " * 8
        full += "\n"
    full = full.replace("0", "1").replace(" ", "0")

    cpp = "const uint8_t IMAGES[][8] = {\n"
    for i in range(len(full.splitlines()[0]) - 8):
        cpp += "  {\n"
        for row in range(8):
            row_content = full.splitlines()[row][i:i+8]
            cpp += "    0b" + row_content + ",\n"
        cpp += "  },\n"
    cpp += "};\nconst int IMAGES_LEN = sizeof(IMAGES) / 8;\n"
    return cpp


import sys

if __name__ == "__main__":
    print(generate(sys.argv[1]))
